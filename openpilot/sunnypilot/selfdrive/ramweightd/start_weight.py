"""
Starting weight for the weight estimator, and identification of the truck's configuration.

The configuration (model year, 2500 or 3500, single or dual rear wheels, cab, bed, two- or four-wheel drive, engine,
transmission, and package: Power Wagon, Rebel or none) comes from the vehicle identification number (VIN,
CarParams.carVin) and from the engine and transmission module part numbers the truck reports at startup
(CarParams.carFw). What each VIN character and part number means comes ONLY from the published-weight table
(ram_hd_weights.json, generated by make_weight_table.py); the only VIN position known here is the model-year
character at position 10, which every North American VIN has. The VIN itself is never logged, stored or published:
only the configuration in words.

Starting weight, in order:
1. the device setting CruiseBaseWeightLb when above 0 (Eric's truck: 8,400 lb with a full tank), minus missing fuel;
2. Ram's published curb weight for the identified configuration, plus the options allowance (OPTIONS_ALLOWANCE_LB),
   plus 250 lb, minus missing fuel. The VIN cannot tell a RamBox from the standard box: the standard box is used and
   the RamBox's extra weight is added to the uncertainty. On a 3500 with the Cummins the VIN cannot tell the standard
   output (68RFE gearbox) from the high output (AS69RC): the engine part number decides when the table knows it,
   otherwise the two are averaged with a wider uncertainty. When only the bed is unknown (a VIN code missing from the
   table), the average over both beds with a wider uncertainty ("tableBedAverage");
3. otherwise the platform's weight from CarParams, with a wide uncertainty.
Curb weights and Eric's figures include a full tank, hence "minus missing fuel". When the fuel level is not
available, the tank is assumed half full, with the uncertainty of not knowing it.
"""
import json
import math
import os
import re
from dataclasses import dataclass, field

from openpilot.sunnypilot.selfdrive.ramweightd.estimator import LB_TO_KG

DEFAULT_TABLE_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ram_hd_weights.json")
TABLE_SCHEMA = 1

CONFIG_FIELDS = ("model_year", "series", "rear_wheels", "cab", "bed", "drive", "engine", "transmission")  # required in each row
OPTIONAL_FIELDS = {"package": None, "box_variant": "standard"}  # row default when absent
ALL_FIELDS = CONFIG_FIELDS + tuple(OPTIONAL_FIELDS)
FIELD_VALUES = {
  "series": ("2500", "3500"),
  "rear_wheels": ("single", "dual"),
  "cab": ("regular", "crew", "mega"),
  "bed": ("short", "long"),
  "drive": ("4x2", "4x4"),
  "engine": ("hemi_6.4", "cummins_so", "cummins_ho"),
  "transmission": ("8HP75", "68RFE", "AS69RC"),
  "package": (None, "power_wagon", "rebel"),
  "box_variant": ("standard", "rambox"),
}

# Eric's truck (edfrahm/SP-RamHD-TICI-Port#8)
ERIC_CONFIGURATION = {"model_year": 2022, "series": "2500", "rear_wheels": "single", "cab": "crew", "bed": "short",
                      "drive": "4x4", "engine": "cummins_so", "transmission": "68RFE"}
ERIC_EMPTY_LB = 8040.
# Options allowance: what a truck that can run openpilot weighs above Ram's published (base trim) curb weight.
# 8,040 lb (Eric's truck empty, full tank) - 7,511 lb (Stellantis 2022 Ram 2500 4x4 weight and tow chart, body builder
# instruction of 07/07/2021, page 5, table "RAM 2500 - 4X4 - CREW CAB - ST - 6'4'' STANDARD BOX": the Tradesman's
# weight with a full fuel tank) = 529 lb.
OPTIONS_ALLOWANCE_LB = 529.
DRIVER_ALLOWANCE_LB = 250.  # driver and everyday gear

DEFAULT_TANK_GAL = 32.  # used only when the table gives no tank size
# Optional larger tank (Crew Cab with the 8 ft box, 2020-2024: 50 gallons instead of 32; owner's manuals' fluid
# capacities). The VIN cannot tell; unless the truck reports its tank size, the larger tank is assumed (decision by
# Eric, edfrahm/SP-RamHD-TICI-Port#8): its extra full-tank fuel is added to the published curb weight (which includes
# a full standard tank), and the starting uncertainty grows by the chance it is really the standard tank (half the
# extra fuel's weight) and by the unpublished weight of the larger tank itself.
LARGE_TANK_SHELL_STD_LB = 30.
# US Department of Energy, Transportation Energy Data Book, edition 40, table 6.17: low-sulfur diesel 7.079 lb per
# US gallon; gasoline 6.0-6.5 (6.25 is the middle)
DEFAULT_DIESEL_LB_PER_GAL = 7.079
DEFAULT_GASOLINE_LB_PER_GAL = 6.25
UNKNOWN_FUEL_FRACTION = 0.5  # fuel level unknown: assume half full

SETTING_STD_KG = 50.    # a weight the owner entered (for example from a scale)
TABLE_STD_KG = 150.     # options and equipment vary from truck to truck
FALLBACK_STD_KG = 600.  # configuration unknown: Ram Heavy Duty trucks range from about 6,000 to 9,000 lb

# VIN position 9 check digit (49 CFR 565): letter values and position weights
_VIN_VALUES = {**{str(d): d for d in range(10)},
               **dict(zip("ABCDEFGH", range(1, 9), strict=True)), **dict(zip("JKLMN", range(1, 6), strict=True)), "P": 7, "R": 9,
               **dict(zip("STUVWXYZ", range(2, 10), strict=True))}
_VIN_WEIGHTS = (8, 7, 6, 5, 4, 3, 2, 10, 0, 9, 8, 7, 6, 5, 4, 3, 2)
_RANGE_RE = re.compile(r"^(\d+)-(\d+)$")


def _positions(position) -> tuple[int, int] | None:
  """A rule's VIN position: one position (5), or a range of positions read as one code ("5-7"). 1-based, inclusive."""
  if isinstance(position, int) and not isinstance(position, bool):
    return (position, position) if 1 <= position <= 17 else None
  m = _RANGE_RE.match(str(position))
  if m:
    a, b = int(m.group(1)), int(m.group(2))
    return (a, b) if 1 <= a <= b <= 17 else None
  return None


@dataclass
class WeightTable:
  configs: list[dict]
  model_year_codes: dict[str, int]
  vin_rules: list[dict]
  part_rules: list[tuple[str, dict]]  # (module kind "engine" or "transmission", rule)
  diesel_lb_per_gal: float = DEFAULT_DIESEL_LB_PER_GAL
  gasoline_lb_per_gal: float = DEFAULT_GASOLINE_LB_PER_GAL
  placeholder: bool = False
  retrieved: str | None = None


def _check_meaning(meaning: dict, where: str) -> None:
  for k, v in meaning.items():
    if k not in ALL_FIELDS:
      raise ValueError(f"weight table: {where} meaning has unknown field {k!r}")
    for x in (v if isinstance(v, list) else [v]):
      if k in FIELD_VALUES and x not in FIELD_VALUES[k]:
        raise ValueError(f"weight table: {where} meaning {k} = {x!r} is not one of {FIELD_VALUES[k]}")


def parse_weight_table(data: dict) -> WeightTable:
  """Checks the table layout (schema 1) and returns it. Raises ValueError on a malformed table."""
  if not isinstance(data, dict) or data.get("schema") != TABLE_SCHEMA:
    raise ValueError(f"weight table: schema must be {TABLE_SCHEMA}")
  configs = data.get("configs", [])
  if not isinstance(configs, list):
    raise ValueError("weight table: configs must be a list")
  rows = []
  for i, c in enumerate(configs):
    if not isinstance(c, dict):
      raise ValueError(f"weight table: configs[{i}] is not an object")
    row = {**OPTIONAL_FIELDS, **c}
    for k in ALL_FIELDS:
      if k not in row:
        raise ValueError(f"weight table: configs[{i}] lacks {k}")
      if k in FIELD_VALUES and row[k] not in FIELD_VALUES[k]:
        raise ValueError(f"weight table: configs[{i}].{k} = {row[k]!r} is not one of {FIELD_VALUES[k]}")
    # the research table's best figure; older layouts call it curb_weight_lb
    row["curb_weight_lb"] = c.get("recommended_curb_weight_lb", c.get("curb_weight_lb"))
    for k in ("curb_weight_lb", "fuel_tank_gal", "fuel_tank_optional_gal"):
      if row.get(k) is not None and not (isinstance(row[k], (int, float)) and row[k] > 0):
        raise ValueError(f"weight table: configs[{i}].{k} must be a positive number or null")
    rows.append(row)
  vin = data.get("vin", {}) or {}
  codes = {str(k): int(v) for k, v in (vin.get("model_year_codes", {}) or {}).items()}
  rules = vin.get("rules", []) or []
  for i, r in enumerate(rules):
    pos = _positions(r.get("position")) if isinstance(r, dict) else None
    if not (pos and isinstance(r.get("code"), str) and len(r["code"]) == pos[1] - pos[0] + 1 and isinstance(r.get("meaning"), dict)):
      raise ValueError(f"weight table: vin.rules[{i}] needs a position (1-17, or a range like 5-7), a code of that length and a meaning")
    _check_meaning(r["meaning"], f"vin.rules[{i}]")
  part_rules = []
  for kind in ("engine", "transmission"):
    for i, r in enumerate(data.get(f"{kind}_parts", []) or []):
      if not (isinstance(r, dict) and isinstance(r.get("part_prefix_or_number"), str) and r["part_prefix_or_number"]):
        raise ValueError(f"weight table: {kind}_parts[{i}] needs part_prefix_or_number")
      _check_meaning({k: v for k, v in r.items() if k in ALL_FIELDS}, f"{kind}_parts[{i}]")
      part_rules.append((kind, r))
  return WeightTable(
    configs=rows,
    model_year_codes=codes,
    vin_rules=rules,
    part_rules=part_rules,
    diesel_lb_per_gal=float(data.get("diesel_lb_per_gal") or DEFAULT_DIESEL_LB_PER_GAL),
    gasoline_lb_per_gal=float(data.get("gasoline_lb_per_gal") or DEFAULT_GASOLINE_LB_PER_GAL),
    placeholder=bool(data.get("placeholder", False)),
    retrieved=data.get("retrieved"),
  )


def load_weight_table(path: str | None = None) -> WeightTable | None:
  """The published-weight table, or None when the file is missing or malformed (the estimator then falls back)."""
  try:
    with open(path or DEFAULT_TABLE_PATH) as f:
      return parse_weight_table(json.load(f))
  except (OSError, ValueError) as e:
    from openpilot.common.swaglog import cloudlog
    cloudlog.warning(f"ramweightd: weight table not usable: {e}")
    return None


def vin_is_valid(vin: str) -> bool:
  if not isinstance(vin, str) or len(vin) != 17 or vin == "0" * 17:
    return False
  vin = vin.upper()
  if any(ch not in _VIN_VALUES for ch in vin):
    return False
  total = sum(_VIN_VALUES[ch] * w for ch, w in zip(vin, _VIN_WEIGHTS, strict=True))
  check = total % 11
  return vin[8] == ("X" if check == 10 else str(check))


# A field's value is one value, or a frozenset of candidates (for example a Cummins of either output).
def _as_set(v) -> frozenset:
  return v if isinstance(v, frozenset) else frozenset([v])


def _merge(fields: dict, conflicts: set, meaning: dict) -> None:
  for k, v in meaning.items():
    if k in conflicts:
      continue
    new = frozenset(v) if isinstance(v, list) else v
    if k in fields:
      both = _as_set(fields[k]) & _as_set(new)
      if not both:
        del fields[k]
        conflicts.add(k)
        continue
      new = next(iter(both)) if len(both) == 1 else frozenset(both)
    fields[k] = new


def decode_vin(vin: str, table: WeightTable) -> tuple[dict, set]:
  """Configuration fields from the VIN, using only the table's rules. Returns (fields, conflicting field names)."""
  fields: dict = {}
  conflicts: set = set()
  if not vin_is_valid(vin):
    return fields, conflicts
  vin = vin.upper()
  year = table.model_year_codes.get(vin[9])
  if year is None:
    return fields, conflicts
  fields["model_year"] = year
  for rule in table.vin_rules:
    years = rule.get("model_years")
    if years and year not in years:
      continue
    a, b = _positions(rule["position"])
    if vin[a - 1:b] == rule["code"].upper():
      _merge(fields, conflicts, rule["meaning"])
  return fields, conflicts


def decode_parts(car_fw, table: WeightTable) -> tuple[dict, set]:
  """Configuration fields from the engine and transmission module part numbers (CarParams.carFw)."""
  fields: dict = {}
  conflicts: set = set()
  for fw in car_fw:
    kind = str(fw.ecu)
    if kind not in ("engine", "transmission"):
      continue
    part = bytes(fw.fwVersion).decode("ascii", errors="ignore").strip().upper()
    if not part:
      continue
    for rule_kind, rule in table.part_rules:
      if rule_kind == kind and part.startswith(rule["part_prefix_or_number"].strip().upper()):
        _merge(fields, conflicts, {k: v for k, v in rule.items() if k in ALL_FIELDS})
  return fields, conflicts


def matching_configs(fields: dict, table: WeightTable) -> list[dict]:
  """Table rows consistent with the identified fields. A truck whose package is not identified is taken to have none
  (the usual case), and the standard box is preferred to the RamBox, which the VIN cannot tell apart."""
  rows = [c for c in table.configs if all(c[k] in _as_set(v) for k, v in fields.items() if k in ALL_FIELDS)]
  if "package" not in fields and any(c["package"] is None for c in rows):
    rows = [c for c in rows if c["package"] is None]
  return rows


@dataclass
class Configuration:
  fields: dict = field(default_factory=dict)
  conflicts: set = field(default_factory=set)

  @property
  def text(self) -> str:
    return describe_configuration(self.fields, self.conflicts)


def identify_configuration(CP, table: WeightTable | None) -> Configuration:
  if table is None:
    return Configuration()
  fields, conflicts = decode_vin(CP.carVin, table)
  part_fields, part_conflicts = decode_parts(CP.carFw, table)
  conflicts |= part_conflicts
  _merge(fields, conflicts, part_fields)
  # what the table implies: a field every matching row agrees on is identified (for example a 2500 with the
  # Cummins has the standard output and the 68RFE)
  rows = matching_configs(fields, table)
  if rows:
    for k in CONFIG_FIELDS + ("package",):
      if k not in conflicts:
        values = {c[k] for c in rows}
        if len(values) == 1:
          fields[k] = next(iter(values))
  return Configuration(fields, conflicts)


_WORDS = {
  "rear_wheels": {"single": "single rear wheels", "dual": "dual rear wheels"},
  "cab": {"regular": "Regular Cab", "crew": "Crew Cab", "mega": "Mega Cab"},
  "bed": {"short": "short bed", "long": "long bed"},
  "drive": {"4x2": "two-wheel drive", "4x4": "four-wheel drive"},
  "engine": {"hemi_6.4": "6.4 L HEMI gasoline engine", "cummins_so": "Cummins 6.7 L diesel, standard output",
             "cummins_ho": "Cummins 6.7 L diesel, high output"},
  "transmission": {"8HP75": "8HP75 eight-speed automatic", "68RFE": "68RFE six-speed automatic",
                   "AS69RC": "AS69RC six-speed automatic"},
  "package": {"power_wagon": "Power Wagon", "rebel": "Rebel"},
}
_FIELD_WORDS = {"model_year": "model year", "series": "series", "rear_wheels": "rear wheels", "cab": "cab", "bed": "bed",
                "drive": "drive", "engine": "engine", "transmission": "transmission", "package": "package"}


def describe_configuration(fields: dict, conflicts: set | None = None) -> str:
  """The configuration in words (never the VIN)."""
  head = " ".join(x for x in (str(fields["model_year"]) if "model_year" in fields else "", "Ram",
                              fields.get("series", "") if not isinstance(fields.get("series"), frozenset) else "") if x)
  parts = [head]
  for k in ("package", "rear_wheels", "cab", "bed", "drive", "engine", "transmission"):
    v = fields.get(k)
    if v is None:
      continue
    if k == "engine" and v == frozenset({"cummins_so", "cummins_ho"}):
      parts.append("Cummins 6.7 L diesel, standard or high output")
    elif isinstance(v, frozenset):
      parts.append(" or ".join(_WORDS[k][x] for x in sorted(v, key=str) if x is not None))
    else:
      parts.append(_WORDS[k][v])
  unknown = [_FIELD_WORDS[k] for k in CONFIG_FIELDS if k not in fields or isinstance(fields[k], frozenset)]
  text = ", ".join(parts)
  if unknown:
    text += "; not identified: " + ", ".join(unknown)
  if conflicts:
    text += "; conflicting: " + ", ".join(_FIELD_WORDS[k] for k in ALL_FIELDS if k in conflicts)
  return text


@dataclass
class StartWeight:
  mass_kg: float
  std_kg: float
  source: str            # "setting", "table", "tableBedAverage" or "fallback" (the message's StartSource names)
  tank_gal: float
  lb_per_gal: float
  fuel_level_known: bool
  detail: str


def fuel_density_lb_per_gal(fields: dict, table: WeightTable | None) -> float:
  diesel = table.diesel_lb_per_gal if table else DEFAULT_DIESEL_LB_PER_GAL
  gasoline = table.gasoline_lb_per_gal if table else DEFAULT_GASOLINE_LB_PER_GAL
  return gasoline if fields.get("engine") == "hemi_6.4" else diesel  # unknown engine: diesel, like most Ram HD


def _identified_rows(rows: list[dict]) -> list[dict] | None:
  """The standard-box rows of an identified configuration, or None when the rows differ in more than the bed (when
  not identified) and the Cummins output with its gearbox (when the VIN says Cummins without the output)."""
  if not rows or not all(c.get("curb_weight_lb") for c in rows):
    return None
  standard = [c for c in rows if c["box_variant"] == "standard"] or rows
  ignore = {"bed"} | ({"engine", "transmission"} if {c["engine"] for c in standard} <= {"cummins_so", "cummins_ho"} else set())
  if len({tuple(c[k] for k in ALL_FIELDS if k not in ignore) for c in standard}) != 1:
    return None
  return standard


def _table_estimate(fields: dict, rows: list[dict]) -> tuple[str, float, float, str] | None:
  """(source, curb weight lb, uncertainty kg, words) from the matching rows, or None when they are too different."""
  standard = _identified_rows(rows)
  if standard is None:
    return None
  curbs = [c["curb_weight_lb"] for c in standard]
  curb = sum(curbs) / len(curbs)
  std_kg = math.hypot(TABLE_STD_KG, (max(curbs) - min(curbs)) * LB_TO_KG / 2.)
  words = []
  rambox = [c["curb_weight_lb"] for c in rows if c["box_variant"] == "rambox"]
  if rambox and len(standard) < len(rows):
    extra_lb = max(rambox) - curb
    std_kg = math.hypot(std_kg, extra_lb * LB_TO_KG)
    words.append(f"standard box (a RamBox would add {extra_lb:.0f} lb)")
  beds = {c["bed"] for c in standard}
  if len({c["engine"] for c in standard}) > 1:
    words.append("average of the standard and high output Cummins")
  if len(beds) > 1:
    std_kg = math.hypot(std_kg, 50.)
    words.append("average of both beds")
    return "tableBedAverage", curb, std_kg, ", ".join(words)
  return "table", curb, std_kg, ", ".join(words)


def choose_start_weight(config: Configuration, table: WeightTable | None, base_weight_lb: float,
                        fuel_level_pct: float | None, cp_mass_kg: float, tank_gal_reported: float | None = None) -> StartWeight:
  """tank_gal_reported: the fuel tank's size as the truck reports it, when available."""
  fields = config.fields
  lb_per_gal = fuel_density_lb_per_gal(fields, table)
  rows = matching_configs(fields, table) if table else []
  standard = [c for c in rows if c["box_variant"] == "standard"] or rows
  tanks = [c["fuel_tank_gal"] for c in standard if c.get("fuel_tank_gal")]
  standard_tank_gal = sum(tanks) / len(tanks) if tanks else DEFAULT_TANK_GAL
  optional = {c.get("fuel_tank_optional_gal") for c in standard}

  # tank size: reported by the truck, else the optional larger tank where one exists, else the standard tank
  tank_std_kg = 0.
  tank_text = ""
  if tank_gal_reported is not None and tank_gal_reported > 0.:
    tank_gal = tank_gal_reported
  elif standard and len(optional) == 1 and (opt := next(iter(optional))) and opt > standard_tank_gal:
    tank_gal = opt
    extra_lb = (opt - standard_tank_gal) * lb_per_gal
    tank_std_kg = math.hypot(LARGE_TANK_SHELL_STD_LB, extra_lb / 2.) * LB_TO_KG
    tank_text = f", assumed optional {opt:.0f} gal tank (+{extra_lb:.0f} lb of fuel over the {standard_tank_gal:.0f} gal tank)"
  else:
    tank_gal = standard_tank_gal
  extra_fuel_lb = (tank_gal - standard_tank_gal) * lb_per_gal  # the published curb weight has a full standard tank

  full_tank_lb = tank_gal * lb_per_gal
  if fuel_level_pct is not None:
    missing_lb = (1. - min(max(fuel_level_pct, 0.), 100.) / 100.) * full_tank_lb
    fuel_std_kg = 0.03 * full_tank_lb * LB_TO_KG
    fuel_text = f"minus {missing_lb:.0f} lb of missing fuel"
  else:
    missing_lb = UNKNOWN_FUEL_FRACTION * full_tank_lb
    fuel_std_kg = full_tank_lb * LB_TO_KG / math.sqrt(12.)
    fuel_text = f"minus {missing_lb:.0f} lb of fuel (level unknown: half of a {tank_gal:.0f} gal tank assumed)"
  known = fuel_level_pct is not None

  if base_weight_lb > 0.:
    mass_lb = base_weight_lb - missing_lb
    return StartWeight(mass_lb * LB_TO_KG, math.hypot(SETTING_STD_KG, fuel_std_kg), "setting", tank_gal, lb_per_gal, known,
                       f"setting {base_weight_lb:.0f} lb (full tank) {fuel_text}")

  est = _table_estimate(fields, rows) if table else None
  if est is not None:
    source, curb, std_kg, words = est
    mass_lb = curb + extra_fuel_lb + OPTIONS_ALLOWANCE_LB + DRIVER_ALLOWANCE_LB - missing_lb
    return StartWeight(mass_lb * LB_TO_KG, math.hypot(std_kg, fuel_std_kg, tank_std_kg), source, tank_gal, lb_per_gal, known,
                       f"published curb weight {curb:.0f} lb" + (f" ({words})" if words else "") + tank_text +
                       f" + options allowance {OPTIONS_ALLOWANCE_LB:.0f} lb + {DRIVER_ALLOWANCE_LB:.0f} lb {fuel_text}")

  return StartWeight(cp_mass_kg, FALLBACK_STD_KG, "fallback", tank_gal, lb_per_gal, known,
                     f"platform weight {cp_mass_kg / LB_TO_KG:.0f} lb from CarParams (configuration or table weight unknown)")


@dataclass
class WeightFloor:
  mass_kg: float | None   # None: no floor
  source: str             # "setting", "table" or "none"
  detail: str


def weight_floor(config: Configuration, table: WeightTable | None, empty_weight_lb: float, fuel_level_pct: float | None,
                 tank_gal: float, lb_per_gal: float) -> WeightFloor:
  """The lowest weight the truck can have: its empty weight minus the fuel not in the tank (Eric's decision,
  edfrahm/SP-RamHD-TICI-Port#8). Empty weight: the setting CruiseEmptyWeightLb when above 0 (Eric's truck: 8,040 lb,
  its sticker weight; whether that includes fuel is not known, so subtracting the missing fuel keeps the floor safe
  either way), else Ram's published curb weight for the identified configuration without the options allowance
  (lower trims may have fewer options; the lightest of the candidate rows), else no floor. The fuel not in the tank is
  the whole tank when the level is not known."""
  if empty_weight_lb > 0.:
    empty_lb, source = empty_weight_lb, "setting"
  else:
    rows = _identified_rows(matching_configs(config.fields, table)) if table else None
    if rows is None:
      return WeightFloor(None, "none", "no floor (configuration not identified and CruiseEmptyWeightLb not set)")
    empty_lb, source = min(c["curb_weight_lb"] for c in rows), "table"
  full_lb = tank_gal * lb_per_gal
  missing_lb = full_lb if fuel_level_pct is None else (1. - min(max(fuel_level_pct, 0.), 100.) / 100.) * full_lb
  words = "level unknown: as if empty" if fuel_level_pct is None else f"{fuel_level_pct:.0f} percent full"
  return WeightFloor((empty_lb - missing_lb) * LB_TO_KG, source,
                     f"{source} empty weight {empty_lb:.0f} lb minus {missing_lb:.0f} lb of fuel not in the tank ({words})")
